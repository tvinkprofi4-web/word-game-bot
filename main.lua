-- UTF-8 разбиение на символы
local function utf8chars(s)
    local t = {}
    for _, code in utf8.codes(s) do table.insert(t, utf8.char(code)) end
    return t
end

-- ТОЧНЫЙ детектор букв (1, 2 или 3 буквы раунда)
local function getLetters()
    local screenCenter = Camera.ViewportSize.X / 2
    local found = {}
    local wordGameUI = PlayerGui:FindFirstChild("WordGameUI")
    if not wordGameUI then return {} end

    -- Способ 1: Ищем контейнер с текстом "Напиши слово" или "букв"
    local promptContainer = nil
    for _, obj in ipairs(wordGameUI:GetDescendants()) do
        if obj:IsA("TextLabel") and obj.Visible then
            local t = obj.Text or ""
            if t:find("Напиши слово") or t:find("слово на") then
                promptContainer = obj.Parent
                break
            end
        end
    end

    local searchScope = promptContainer or wordGameUI:FindFirstChild("Match", true) or wordGameUI

    -- Сканируем плитки букв внутри контейнера
    for _, obj in ipairs(searchScope:GetDescendants()) do
        pcall(function()
            if obj:IsA("TextLabel") and obj.Visible then
                -- Игнорируем заголовки, таймеры, ранги, уровни
                if obj.Name ~= "Heading" and obj.Name ~= "Title" and obj.Name ~= "Label" and obj.Name ~= "HeavyFill" then
                    local t = obj.Text:gsub("%s+", "")
                    local ch = utf8chars(t)
                    -- Плитка содержит 1 русскую букву
                    if #ch == 1 and toCyr(ch[1]) then
                        local posX = obj.AbsolutePosition.X + obj.AbsoluteSize.X / 2
                        local posY = obj.AbsolutePosition.Y
                        local distToCenter = math.abs(posX - screenCenter)
                        -- Центральные плитки раунда (в пределах 180 px от центра экрана)
                        if distToCenter <= 180 and posY < Camera.ViewportSize.Y * 0.65 then
                            -- Не дублировать плитки
                            local exists = false
                            for _, f in ipairs(found) do
                                if math.abs(f.x - posX) < 15 then exists = true; break end
                            end
                            if not exists then
                                table.insert(found, { char = toCyr(ch[1]), x = posX })
                            end
                        end
                    end
                end
            end
        end)
    end

    table.sort(found, function(a, b) return a.x < b.x end)
    local chars = {}
    for _, item in ipairs(found) do table.insert(chars, item.char) end
    return chars
end

-- ПОДБОР СЛОВА ДЛЯ 1, 2 ИЛИ 3 БУКВ
local function pickBestWord(letters)
    local n = #letters
    if n == 0 then return nil end

    local candidates = {}
    local c1 = letters[1]

    if n == 1 then
        -- 1 БУКВА: слово начинается на эту букву
        local pool = DICT[c1] or {}
        for _, w in ipairs(pool) do
            if not usedWords[w] then table.insert(candidates, w) end
        end
    elseif n == 2 then
        -- 2 БУКВЫ: например [М] [Й] или [Н] [Й]
        local c2 = letters[2]
        -- Приоритет 1: Начинается на c1, заканчивается на c2 (МУЗЕЙ, МАЙ, НАТРИЙ, НОВЫЙ)
        local pool = DICT[c1] or {}
        for _, w in ipairs(pool) do
            if not usedWords[w] then
                local ch = utf8chars(w)
                if toCyr(ch[#ch]) == c2 then
                    table.insert(candidates, w)
                end
            end
        end
        -- Приоритет 2: Начинается на префикс c1..c2 (КОМПЬЮТЕР, ПРОЕКТ)
        if #candidates == 0 then
            local prefix = c1 .. c2
            for _, w in ipairs(pool) do
                if not usedWords[w] and w:find("^" .. prefix) then
                    table.insert(candidates, w)
                end
            end
        end
        -- Приоритет 3: Любое слово на c1
        if #candidates == 0 then
            for _, w in ipairs(pool) do
                if not usedWords[w] then table.insert(candidates, w) end
            end
        end
    elseif n >= 3 then
        -- 3 БУКВЫ: например [П] [Р] [О]
        local c2, c3 = letters[2], letters[3]
        local prefix = c1 .. c2 .. c3
        local pool = DICT[c1] or {}
        -- Приоритет 1: слово начинается на эту комбинацию
        for _, w in ipairs(pool) do
            if not usedWords[w] and w:find("^" .. prefix) then
                table.insert(candidates, w)
            end
        end
        -- Приоритет 2: слово содержит эту комбинацию
        if #candidates == 0 then
            for _, w in ipairs(ALL_WORDS) do
                if not usedWords[w] and w:find(prefix) then
                    table.insert(candidates, w)
                end
            end
        end
        -- Приоритет 3: начинается на c1, заканчивается на c3
        if #candidates == 0 then
            for _, w in ipairs(pool) do
                if not usedWords[w] then
                    local ch = utf8chars(w)
                    if toCyr(ch[#ch]) == c3 then table.insert(candidates, w) end
                end
            end
        end
    end

    -- Если все слова были использованы — берём из полного пула c1
    if #candidates == 0 then
        candidates = DICT[c1] or {}
    end
    if #candidates == 0 then return nil end

    -- Сортировка: выбираем САМЫЕ БОЛЬШИЕ слова (длинные)
    table.sort(candidates, function(a, b)
        return #utf8chars(a) > #utf8chars(b)
    end)

    -- Случайный выбор из топ-3 самых длинных
    local topN = math.min(#candidates, 3)
    local chosen = candidates[math.random(1, topN)]
    usedWords[chosen] = true
    return chosen
end

-- Поиск поля ввода TypingCapture
local function findTypingBox()
    local wordGameUI = PlayerGui:FindFirstChild("WordGameUI")
    if not wordGameUI then return nil end
    for _, obj in ipairs(wordGameUI:GetDescendants()) do
        if obj:IsA("TextBox") and obj.Name == "TypingCapture" then
            return obj
        end
    end
    return nil
end

-- ВВОД СЛОВА В ИГРУ
local isTyping = false
local function autoAnswer()
    if isTyping then return end
    local letters = getLetters()
    if #letters == 0 then
        showStatus("Буквы раунда не найдены! Встань за стол.", true)
        return
    end

    local letterStr = table.concat(letters, " ")
    local word = pickBestWord(letters)
    if not word then
        showStatus("Нет слов под буквы: " .. letterStr, true)
        return
    end

    local typingBox = findTypingBox()
    if not typingBox then
        showStatus("Поле ввода TypingCapture не найдено!", true)
        return
    end

    isTyping = true
    showStatus("Буквы: [" .. letterStr .. "] -> Слово: " .. word .. "...")

    -- Внимание: в этой игре ПЕРВАЯ буква уже стоит в 1-й плитке!
    -- Мы печатаем только остаток слова (со 2-й буквы), чтобы не было ААКУЛА!
    local chars = utf8chars(word)
    local tail = {}
    for i = 2, #chars do table.insert(tail, chars[i]) end

    -- Активация поля ввода
    typingBox:CaptureFocus()
    typingBox.Text = ""
    task.wait(0.08)

    -- Скорость печати: ~1.5 - 2.0 секунды на слово
    local totalTime = 1.3 + math.random() * 0.6
    local perChar = totalTime / math.max(#tail, 1)

    for _, c in ipairs(tail) do
        typingBox.Text = typingBox.Text .. string.lower(c)
        task.wait(perChar + (math.random() - 0.5) * perChar * 0.3)
    end

    task.wait(0.1)
    typingBox:ReleaseFocus(true)

    -- Нажимаем Enter для отправки слова
    VIM:SendKeyEvent(true, Enum.KeyCode.Return, false, game)
    task.wait(0.05)
    VIM:SendKeyEvent(false, Enum.KeyCode.Return, false, game)

    showStatus("Отправлено: " .. word .. " | Использовано: " .. tostring(tableCount(usedWords)))
    isTyping = false
end

function tableCount(t)
    local c = 0
    for _ in pairs(t) do c = c + 1 end
    return c
end

-- БИНДЫ: Q (или F2) для ответа, Ctrl + R для сброса
UIS.InputBegan:Connect(function(input, gp)
    if gp then return end
    if input.KeyCode == Enum.KeyCode.Q or input.KeyCode == Enum.KeyCode.F2 then
        autoAnswer()
    elseif input.KeyCode == Enum.KeyCode.R and UIS:IsKeyDown(Enum.KeyCode.LeftControl) then
        _G.UsedWordsHistory = {}
        usedWords = _G.UsedWordsHistory
        showStatus("Память слов очищена! Новый раунд.")
    end
end)

